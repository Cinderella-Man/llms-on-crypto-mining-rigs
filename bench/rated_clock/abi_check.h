/*
 * Compile-time checks of every size, offset and value rated_clock.c relies on, for x86_64. rated_clock.c includes
 * this file after nvidia/nvrm_abi.h (the excerpts); abi_upstream.c includes it after NVIDIA's own headers at tag
 * 580.178.04. Both compiling means the excerpts match the upstream headers.
 * SPDX-License-Identifier: MIT
 */
#ifndef RATED_CLOCK_ABI_CHECK_H
#define RATED_CLOCK_ABI_CHECK_H

#include <stddef.h>
#include <sys/ioctl.h>

#define RC_ASSERT(cond) _Static_assert(cond, #cond)

/* escapes and ioctl numbers */
RC_ASSERT(NV_IOCTL_MAGIC == 'F');
RC_ASSERT(NV_ESC_CARD_INFO == 200);
RC_ASSERT(NV_ESC_CHECK_VERSION_STR == 210);
RC_ASSERT(NV_ESC_RM_FREE == 0x29);
RC_ASSERT(NV_ESC_RM_CONTROL == 0x2A);
RC_ASSERT(NV_ESC_RM_ALLOC == 0x2B);
RC_ASSERT(NV_RM_API_VERSION_STRING_LENGTH == 64);
RC_ASSERT(NV_RM_API_VERSION_CMD_STRICT == 0);
RC_ASSERT(NV_RM_API_VERSION_REPLY_RECOGNIZED == 1);

/* classes and commands */
RC_ASSERT(NV01_ROOT == 0x0);
RC_ASSERT(NV01_DEVICE_0 == 0x80);
RC_ASSERT(NV20_SUBDEVICE_0 == 0x2080);
RC_ASSERT(NV0000_CTRL_CMD_GPU_GET_ID_INFO_V2 == 0x205);
RC_ASSERT(NV2080_CTRL_CMD_PERF_RATED_TDP_GET_CONTROL == 0x2080206e);
RC_ASSERT(NV2080_CTRL_CMD_PERF_RATED_TDP_SET_CONTROL == 0x2080206f);
RC_ASSERT(NV2080_CTRL_PERF_RATED_TDP_STATUS_PARAMS_MESSAGE_ID == 0x6D);

/* the rated-clock enums */
RC_ASSERT(NV2080_CTRL_PERF_RATED_TDP_CLIENT_RM == 0);
RC_ASSERT(NV2080_CTRL_PERF_RATED_TDP_CLIENT_WAR_BUG_1785342 == 1);
RC_ASSERT(NV2080_CTRL_PERF_RATED_TDP_CLIENT_GLOBAL == 2);
RC_ASSERT(NV2080_CTRL_PERF_RATED_TDP_CLIENT_OS == 3);
RC_ASSERT(NV2080_CTRL_PERF_RATED_TDP_CLIENT_PROFILE == 4);
RC_ASSERT(NV2080_CTRL_PERF_RATED_TDP_CLIENT_NUM_CLIENTS == 5);
RC_ASSERT(NV2080_CTRL_PERF_RATED_TDP_ACTION_DEFAULT == 0);
RC_ASSERT(NV2080_CTRL_PERF_RATED_TDP_ACTION_FORCE_EXCEED == 1);
RC_ASSERT(NV2080_CTRL_PERF_RATED_TDP_ACTION_FORCE_LIMIT == 2);
RC_ASSERT(NV2080_CTRL_PERF_RATED_TDP_ACTION_FORCE_LOCK == 3);
RC_ASSERT(NV2080_CTRL_PERF_RATED_TDP_ACTION_FORCE_FLOOR == 4);
RC_ASSERT(NV2080_CTRL_PERF_VPSTATE_RATED_TDP == 0);
RC_ASSERT(NV2080_CTRL_PERF_VPSTATE_TURBO_BOOST == 1);

/* structure layouts */
RC_ASSERT(sizeof(nv_pci_info_t) == 12);
RC_ASSERT(offsetof(nv_pci_info_t, vendor_id) == 8);
RC_ASSERT(sizeof(nv_ioctl_card_info_t) == 72);
RC_ASSERT(offsetof(nv_ioctl_card_info_t, pci_info) == 4);
RC_ASSERT(offsetof(nv_ioctl_card_info_t, gpu_id) == 16);
RC_ASSERT(offsetof(nv_ioctl_card_info_t, reg_address) == 24);
RC_ASSERT(offsetof(nv_ioctl_card_info_t, minor_number) == 56);
RC_ASSERT(sizeof(nv_ioctl_rm_api_version_t) == 72);
RC_ASSERT(sizeof(NVOS00_PARAMETERS) == 16);
RC_ASSERT(sizeof(NVOS21_PARAMETERS) == 32);
RC_ASSERT(offsetof(NVOS21_PARAMETERS, pAllocParms) == 16);
RC_ASSERT(offsetof(NVOS21_PARAMETERS, status) == 28);
RC_ASSERT(sizeof(NVOS54_PARAMETERS) == 32);
RC_ASSERT(offsetof(NVOS54_PARAMETERS, params) == 16);
RC_ASSERT(offsetof(NVOS54_PARAMETERS, status) == 28);
RC_ASSERT(sizeof(NV0080_ALLOC_PARAMETERS) == 56);
RC_ASSERT(offsetof(NV0080_ALLOC_PARAMETERS, vaSpaceSize) == 24);
RC_ASSERT(offsetof(NV0080_ALLOC_PARAMETERS, vaMode) == 48);
RC_ASSERT(sizeof(NV2080_ALLOC_PARAMETERS) == 4);
RC_ASSERT(sizeof(NV0000_CTRL_GPU_GET_ID_INFO_V2_PARAMS) == 32);
RC_ASSERT(offsetof(NV0000_CTRL_GPU_GET_ID_INFO_V2_PARAMS, deviceInstance) == 8);
RC_ASSERT(sizeof(NV2080_CTRL_PERF_RATED_TDP_CONTROL_PARAMS) == 12);
RC_ASSERT(offsetof(NV2080_CTRL_PERF_RATED_TDP_CONTROL_PARAMS, vPstateType) == 8);
RC_ASSERT(sizeof(NV2080_CTRL_PERF_RATED_TDP_STATUS_PARAMS) == 56);
RC_ASSERT(offsetof(NV2080_CTRL_PERF_RATED_TDP_STATUS_PARAMS, output) == 8);
RC_ASSERT(offsetof(NV2080_CTRL_PERF_RATED_TDP_STATUS_PARAMS, outputVPstate) == 12);
RC_ASSERT(offsetof(NV2080_CTRL_PERF_RATED_TDP_STATUS_PARAMS, inputs) == 16);
RC_ASSERT(offsetof(NV2080_CTRL_PERF_RATED_TDP_STATUS_PARAMS, vPstateTypes) == 36);

/* the request numbers the tool sends */
RC_ASSERT(_IOWR(NV_IOCTL_MAGIC, NV_ESC_RM_ALLOC, NVOS21_PARAMETERS) == 0xc020462b);
RC_ASSERT(_IOWR(NV_IOCTL_MAGIC, NV_ESC_RM_CONTROL, NVOS54_PARAMETERS) == 0xc020462a);
RC_ASSERT(_IOWR(NV_IOCTL_MAGIC, NV_ESC_RM_FREE, NVOS00_PARAMETERS) == 0xc0104629);
RC_ASSERT(_IOWR(NV_IOCTL_MAGIC, NV_ESC_CHECK_VERSION_STR, nv_ioctl_rm_api_version_t) == 0xc04846d2);

#endif /* RATED_CLOCK_ABI_CHECK_H */
